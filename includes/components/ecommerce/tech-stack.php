<script>
(function() {
  const tabs = document.querySelectorAll('.ecom-tech-tab-btn');
  const cards = document.querySelectorAll('#ecom-interactive-tech-grid .tech-card');

  function filterTech(category) {
    let count = 0;
    cards.forEach(card => {
      const match = (category === 'all' || card.getAttribute('data-category') === category);
      if (match) {
        card.style.display = 'flex';
        card.style.opacity = '0';
        card.style.transform = 'translateY(12px)';
        setTimeout(() => {
          card.style.transition = 'all 0.35s cubic-bezier(0.2, 0.8, 0.2, 1)';
          card.style.opacity = '1';
          card.style.transform = 'translateY(0)';
        }, count * 25);
        count++;
      } else {
        card.style.display = 'none';
      }
    });
  }

  tabs.forEach(tab => {
    tab.addEventListener('click', function() {
      tabs.forEach(t => t.classList.remove('active'));
      this.classList.add('active');
      const cat = this.getAttribute('data-filter') || 'all';
      filterTech(cat);
    });
  });

  const container = document.getElementById('ecom-interactive-tech-grid');
  if (container) {
    container.addEventListener('mousemove', function(e) {
      const rect = container.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;
      container.style.setProperty('--mouse-x', x + 'px');
      container.style.setProperty('--mouse-y', y + 'px');
    });

    cards.forEach(cell => {
      cell.addEventListener('mousemove', function(e) {
        const rect = cell.getBoundingClientRect();
        const x = e.clientX - rect.left - rect.width / 2;
        const y = e.clientY - rect.top - rect.height / 2;
        const rotateX = (-y / (rect.height / 2)) * 10;
        const rotateY = (x / (rect.width / 2)) * 10;
        cell.style.transform = `perspective(800px) rotateX(${rotateX.toFixed(2)}deg) rotateY(${rotateY.toFixed(2)}deg) translateY(-6px) scale3d(1.03, 1.03, 1.03)`;
      });

      cell.addEventListener('mouseleave', function() {
        cell.style.transform = '';
      });
    });
  }
})();
</script>
